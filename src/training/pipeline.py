"""
The training pipeline shared by scripts/train.py (one run from a config file) and scripts/search.py
(many runs generated by a hyperparameter search):

- prepare_data: lineage checks, loading and pixel cleaning, done once and reused by every run
- build_components: datasets, model, loss and optimizer for one configuration
- run_sanity_check: overfit a single batch before any real training
- train_and_log: a full training run, recorded in MLflow
"""

import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import mlflow
import numpy as np
import torch
from torch import nn
from torch.optim.lr_scheduler import CosineAnnealingLR, LinearLR, LRScheduler, SequentialLR
from torch.utils.data import DataLoader

from src.common.config_schema import DatasetConfig, ModelConfig, SplitConfig, TrainConfig, load_dataset_config, load_split_config
from src.common.hashing import file_sha256
from src.data.cleaning import apply_invalid_pixel_policy
from src.data.dataset import DiscreteMapDataset, build_split_datasets, seed_worker
from src.data.io import load_npz_arrays
from src.data.split import META_FILE, SplitResult, load_split, load_split_meta
from src.data.transforms import RandomDihedral, encoded_channels
from src.models.factory import build_model
from src.models.profiling import count_flops, count_parameters
from src.training.class_balance import compute_pos_weight, expected_initial_bce
from src.training.losses import build_loss
from src.training.tracking import EFFECTIVE_TRAIN_CONFIG, flatten_params, git_tags, setup_experiment
from src.training.trainer import FitResult, fit, overfit_single_batch, set_seed

SANITY_BATCH_SIZE = 32
SANITY_STEPS = 200
# Recorded as a run tag, so analysis scripts find the checkpoint without hard-coding its path
CHECKPOINT_ARTIFACT = "checkpoints/model.pt"
# Warmup starts from this fraction of the learning rate
WARMUP_START_FACTOR = 0.1


# ========== data ==========


@dataclass(frozen=True)
class PreparedData:
    dataset_cfg: DatasetConfig
    split_cfg: SplitConfig
    split: SplitResult
    split_meta: dict[str, Any]
    source_sha256: str
    images: np.ndarray
    labels: np.ndarray
    # Number of discrete pixel categories, checked to be set
    num_values: int
    cleaning_report: dict[str, Any]


def prepare_data(split_name: str) -> PreparedData:
    """
    Everything that depends neither on the model nor on the hyperparameters, done once: a search
    reuses it for every trial instead of reloading and re-checking the data each time.
    """
    split_cfg = load_split_config(split_name)
    dataset_cfg = load_dataset_config(split_cfg.dataset)
    if dataset_cfg.num_pixel_values is None:
        raise ValueError("Training expects discrete-valued maps; set num_pixel_values in the dataset config.")

    # Data lineage: the split must have been created from exactly this data file
    split_meta = load_split_meta(split_cfg.output_dir)
    source_sha256 = file_sha256(dataset_cfg.source_path)
    if split_meta.get("source_sha256") != source_sha256:
        raise RuntimeError(f"{dataset_cfg.source_path.name} does not match the file split '{split_name}' was created from; regenerate the split or restore the data file.")

    images, labels = load_npz_arrays(dataset_cfg.source_path, dataset_cfg.image_key, dataset_cfg.label_key)
    # Validate every image at once, before any model or MLflow run is created
    images, cleaning_report = apply_invalid_pixel_policy(images, dataset_cfg.num_pixel_values, dataset_cfg.invalid_pixel_policy)
    if cleaning_report["invalid_pixels"]:
        print(f"Imputed {cleaning_report['invalid_pixels']} out-of-range pixels in {cleaning_report['invalid_images']} images: {cleaning_report['replaced_with']}")

    return PreparedData(
        dataset_cfg=dataset_cfg,
        split_cfg=split_cfg,
        split=load_split(split_cfg.output_dir),
        split_meta=split_meta,
        source_sha256=source_sha256,
        images=images,
        labels=labels,
        num_values=dataset_cfg.num_pixel_values,
        cleaning_report=cleaning_report,
    )


# ========== components ==========


@dataclass
class Components:
    model: nn.Module
    loss_fn: nn.Module
    optimizer: torch.optim.Optimizer
    datasets: dict[str, DiscreteMapDataset]
    in_channels: int
    pos_weight: np.ndarray | None


def build_components(train_cfg: TrainConfig, model_cfg: ModelConfig, data: PreparedData, device: torch.device) -> Components:
    """
    Seeded first, so that a configuration and a seed always produce the same initial weights and
    the same augmentation stream. The learning-rate scheduler is built separately (build_scheduler):
    a warmup scheduler lowers the learning rate as soon as it is created, which the single-batch
    sanity check must not inherit.
    """
    set_seed(train_cfg.seed)
    train_transform = RandomDihedral(seed=train_cfg.seed) if train_cfg.augment else None
    datasets = build_split_datasets(data.images, data.labels, data.split, data.num_values, train_cfg.encoding, train_transform)

    in_channels = encoded_channels(data.num_values, train_cfg.encoding)
    model = build_model(
        model_cfg.name,
        data.dataset_cfg.num_classes,
        in_channels,
        model_cfg.pretrained,
        model_cfg.small_input_stem,
        width=model_cfg.width,
        depths=tuple(model_cfg.depths),
    ).to(device)

    # Class weights come from the training split only
    pos_weight = compute_pos_weight(data.labels[data.split.train_idx], train_cfg.pos_weight.mode, train_cfg.pos_weight.max_value)
    loss_fn = build_loss(pos_weight).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=train_cfg.learning_rate, weight_decay=train_cfg.weight_decay)
    return Components(model=model, loss_fn=loss_fn, optimizer=optimizer, datasets=datasets, in_channels=in_channels, pos_weight=pos_weight)


def build_scheduler(optimizer: torch.optim.Optimizer, cfg: TrainConfig) -> LRScheduler | None:
    """
    Per-epoch learning-rate schedule: an optional linear warmup from WARMUP_START_FACTOR of the rate,
    then cosine annealing to 0 over the remaining epochs, or a constant rate with scheduler "none".
    Without warmup this is exactly the cosine schedule used before warmup existed.
    """
    main = CosineAnnealingLR(optimizer, T_max=cfg.epochs - cfg.warmup_epochs) if cfg.scheduler == "cosine" else None
    if cfg.warmup_epochs == 0:
        return main
    warmup = LinearLR(optimizer, start_factor=WARMUP_START_FACTOR, end_factor=1.0, total_iters=cfg.warmup_epochs)
    if main is None:
        return warmup  # after the warmup, LinearLR holds the full rate
    return SequentialLR(optimizer, schedulers=[warmup, main], milestones=[cfg.warmup_epochs])


def build_loaders(datasets: dict[str, DiscreteMapDataset], cfg: TrainConfig, device: torch.device) -> dict[str, DataLoader]:
    common: dict[str, Any] = {
        "batch_size": cfg.batch_size,
        "num_workers": cfg.num_workers,
        "pin_memory": device.type == "cuda",
        "worker_init_fn": seed_worker,
        "persistent_workers": cfg.num_workers > 0,
    }
    # A dedicated generator makes the shuffling order reproducible from the config seed
    generator = torch.Generator().manual_seed(cfg.seed)
    return {
        "train": DataLoader(datasets["train"], shuffle=True, generator=generator, **common),
        "val": DataLoader(datasets["val"], shuffle=False, **common),
    }


# ========== sanity check ==========


def run_sanity_check(components: Components, data: PreparedData, cfg: TrainConfig, device: torch.device) -> bool:
    # Random training samples, not the first ones: split indices are sorted and the data file is
    # ordered by class, so the first 32 samples would all share one label combination and
    # "overfitting" them would prove almost nothing.
    batch_idx = np.random.default_rng(cfg.seed).choice(data.split.train_idx, size=SANITY_BATCH_SIZE, replace=False)
    batch = DiscreteMapDataset(data.images, data.labels, batch_idx, data.num_values, cfg.encoding, transform=None)
    batch_images = torch.stack([batch[i][0] for i in range(len(batch))])
    batch_targets = torch.stack([batch[i][1] for i in range(len(batch))])

    print(f"Sanity check: overfitting one batch of {SANITY_BATCH_SIZE} training samples for {SANITY_STEPS} steps on {device}")
    result = overfit_single_batch(components.model, batch_images, batch_targets, components.loss_fn, components.optimizer, device, steps=SANITY_STEPS)
    expected = expected_initial_bce(data.labels[batch_idx], components.pos_weight)

    print(f"  initial loss : {result['initial_loss']:.4f}  (expected about {expected:.4f} for an untrained model)")
    print(f"  final loss   : {result['final_loss']:.4f}")
    print(f"  exact match  : {result['exact_match']:.1%} of the batch")

    if not 0.5 * expected <= result["initial_loss"] <= 2.0 * expected:
        print("  WARNING: the initial loss is far from the expected value; check the model output and the targets.")
    passed = result["exact_match"] == 1.0 and result["final_loss"] < 0.1 * result["initial_loss"]
    print("PASS" if passed else "FAIL: the model could not fit a single batch; fix this before any real training.")
    return passed


# ========== full training run ==========


@dataclass
class TrainingOutcome:
    run_id: str
    fit: FitResult
    # The metrics logged at each epoch, in order
    history: list[dict[str, float]]
    num_parameters: int
    flops: int
    val_samples: int

    def mean_val_errors(self, last_k: int) -> float:
        """Misclassified validation samples, averaged over the last `last_k` epochs (the same measure as compare_runs.py)."""
        exact_match = np.mean([record["val_exact_match"] for record in self.history[-last_k:]])
        return float((1.0 - exact_match) * self.val_samples)


def train_and_log(
    train_cfg: TrainConfig,
    model_cfg: ModelConfig,
    data: PreparedData,
    device: torch.device,
    *,
    run_name: str,
    tags: dict[str, str],
    config_files: list[Path],
) -> TrainingOutcome:
    """
    Train one configuration and record everything in MLflow: parameters, per-epoch metrics, the
    configs used (`config_files` plus the model config, which a search generates rather than reads
    from a file), and a checkpoint that is enough to rebuild the model.
    """
    components = build_components(train_cfg, model_cfg, data, device)
    scheduler = build_scheduler(components.optimizer, train_cfg)
    loaders = build_loaders(components.datasets, train_cfg, device)
    model = components.model
    num_parameters = count_parameters(model)
    # Per image, at the dataset's input size (batch of 1)
    flops = count_flops(model, (1, components.in_channels, *data.images.shape[1:]))
    val_samples = len(components.datasets["val"])

    history: list[dict[str, float]] = []

    def on_epoch_end(record: dict[str, float], epoch: int) -> None:
        history.append(record)
        mlflow.log_metrics(record, step=epoch)

    setup_experiment(train_cfg.experiment_name)
    with mlflow.start_run(run_name=run_name) as run, tempfile.TemporaryDirectory() as tmp_dir:
        mlflow.set_tags({**git_tags(), "checkpoint_artifact": CHECKPOINT_ARTIFACT, **tags})
        mlflow.log_params(
            {
                **flatten_params(train_cfg.model_dump(mode="json")),
                **flatten_params(model_cfg.model_dump(mode="json"), prefix="model_cfg"),
                "dataset": data.dataset_cfg.name,
                "split_digest": data.split_meta["split_digest"],
                "invalid_pixels_imputed": data.cleaning_report["invalid_pixels"] if data.cleaning_report["policy"] == "neighbor_mode" else 0,
                "source_sha256": data.source_sha256,
                "in_channels": components.in_channels,
                "num_parameters": num_parameters,
                "flops": flops,
                "device": device.type,
                # Lets comparisons turn exact-match rates into numbers of misclassified samples
                "val_samples": val_samples,
            }
        )
        # The exact configs used, so the run can be reproduced even after the YAML files change.
        # train.json and model.json are the effective configs, after command-line overrides or as
        # generated by a search; analysis scripts read them rather than the source files.
        for path in config_files:
            mlflow.log_artifact(str(path), artifact_path="config")
        mlflow.log_dict(train_cfg.model_dump(mode="json"), EFFECTIVE_TRAIN_CONFIG)
        mlflow.log_dict(model_cfg.model_dump(mode="json"), "config/model.json")
        mlflow.log_artifact(str(data.split_cfg.output_dir / META_FILE), artifact_path="config")
        if components.pos_weight is not None:
            mlflow.log_dict(dict(zip(data.dataset_cfg.class_names, components.pos_weight.tolist(), strict=True)), "config/pos_weight.json")
        mlflow.log_dict(data.cleaning_report, "config/pixel_cleaning.json")

        result = fit(
            model,
            loaders["train"],
            loaders["val"],
            components.loss_fn,
            components.optimizer,
            epochs=train_cfg.epochs,
            device=device,
            class_names=data.dataset_cfg.class_names,
            monitor=train_cfg.monitor,
            scheduler=scheduler,
            early_stopping_patience=train_cfg.early_stopping_patience,
            on_epoch_end=on_epoch_end,
            restore_best=train_cfg.checkpoint == "best",
        )

        # The best epoch is always logged for information; the saved model follows train_cfg.checkpoint
        saved_epoch = result.best_epoch if train_cfg.checkpoint == "best" else result.epochs_run
        saved_score = result.best_score if train_cfg.checkpoint == "best" else result.final_score
        mlflow.log_metrics(
            {
                "best_epoch": result.best_epoch,
                f"best_{train_cfg.monitor}": result.best_score,
                f"final_{train_cfg.monitor}": result.final_score,
                "saved_epoch": saved_epoch,
                "epochs_run": result.epochs_run,
            }
        )
        mlflow.log_dict(result.best_metrics, "metrics/best_val_metrics.json")
        mlflow.log_dict(result.final_metrics, "metrics/final_val_metrics.json")

        # Everything needed to rebuild the model for evaluation or ONNX export later
        checkpoint_path = Path(tmp_dir) / Path(CHECKPOINT_ARTIFACT).name
        torch.save(
            {
                "model_state": model.state_dict(),
                "model_config": model_cfg.model_dump(mode="json"),
                "num_classes": data.dataset_cfg.num_classes,
                "in_channels": components.in_channels,
                "encoding": train_cfg.encoding,
                "class_names": data.dataset_cfg.class_names,
                "epoch": saved_epoch,
                "selection": train_cfg.checkpoint,
            },
            checkpoint_path,
        )
        mlflow.log_artifact(str(checkpoint_path), artifact_path=str(Path(CHECKPOINT_ARTIFACT).parent))
        print(
            f"Saved the {train_cfg.checkpoint} model: epoch {saved_epoch}, {train_cfg.monitor} {saved_score:.4f} "
            f"(best epoch {result.best_epoch}: {result.best_score:.4f}) | run {run.info.run_id}"
        )

    return TrainingOutcome(run_id=run.info.run_id, fit=result, history=history, num_parameters=num_parameters, flops=flops, val_samples=val_samples)
